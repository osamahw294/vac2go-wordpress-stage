#!/usr/bin/env python3
"""
Build the Water category knowledge from Vac2Go's "Water_Truck_AI_Advisor.docx"
(received 2026-10-15, client answer to Q2).

    python3 -I phase-2/tools/build_water.py

Input:  phase-2/work/client-2026-10-15/water.txt (text of the client's .docx; not in git)
Output: wp-content/plugins/vac2go-ai-advisor/kb/categories/water.md
        wp-content/plugins/vac2go-ai-advisor/kb/EDITS-WATER.md

As with Round 1 and Round 2, questions and answers are carried over word for word
apart from the EDITS below. Every edit must match exactly once, or the build stops.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "phase-2/work/client-2026-10-15/water.txt"
KB = ROOT / "wp-content/plugins/vac2go-ai-advisor/kb"

# (exact text in an answer, replacement, reason)
EDITS = [
    ("then route the customer to the RSM for a recommendation rather than quoting numbers.",
     "then route the customer to their Vac2Go branch for a recommendation rather than quoting numbers.",
     "\"RSM\" is an internal term; the branch list gives the customer the branch and its phone number."),
]

SUMMARY = (
    "Vac2Go rents one water truck: the Load King 4,000-gallon water truck, available at all Vac2Go branches, "
    "in one standard configuration (front, side and rear air-operated spray bars, a 50 ft hose reel with a "
    "fireman's nozzle, a shaft-driven pump, a hydrant fill hose and a pond/creek suction kit; no water cannon). "
    "It is used for dust suppression, soil compaction, site and equipment washdown, and on-site water supply. "
    "It is non-potable only: never for drinking water or food-grade use, and clean-water service only (no "
    "wastewater, sludge or contaminated liquids, which belong in a vacuum or liquid vacuum truck). A Class B CDL "
    "is required. The customer supplies the water, normally from a hydrant. Vac2Go's water trucks are never a "
    "refill source for hydro excavators or combination units; suggest one only when the customer describes "
    "dust, compaction or washdown needs. For more than 4,000 gallons delivered to one point, the customer needs "
    "a tanker or frac tank from another provider."
)


def parse(text):
    """[[group title, [[question, [answer lines]]]]]"""
    groups, group, qa = [], None, None
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        m = re.match(r"^Group ([A-Z]): (.+)$", line)
        if m:
            group = [f"Group {m.group(1)}: {m.group(2)}", []]
            groups.append(group)
            qa = None
            continue
        if group is None or line.startswith("Status:"):
            continue  # document header and per-group status notes
        if raw.startswith("\t•") or line.startswith("•"):
            qa = [re.sub(r"^•\s*", "", line), []]
            group[1].append(qa)
            continue
        if qa is not None:
            qa[1].append(re.sub(r"^Answer:\s*", "", line))
    return groups


def main():
    if not SRC.exists():
        sys.exit(f"missing source: {SRC}")
    groups = parse(SRC.read_text(encoding="utf-8"))
    counts = [len(g[1]) for g in groups]
    assert counts == [10, 7, 5], counts

    log = []
    for old, new, why in EDITS:
        hits = [(qa, k) for g in groups for qa in g[1] for k, a in enumerate(qa[1]) if old in a]
        assert len(hits) == 1, f"edit must match exactly once: {old[:60]!r} (matched {len(hits)})"
        qa, k = hits[0]
        qa[1][k] = qa[1][k].replace(old, new)
        log.append((qa[0], old, new, why))

    out = ["# Water", "", "## Summary", "", SUMMARY, "", "## Questions and answers", "",
           "From Vac2Go's Water Q&A (2026-10-15). Answer from these, keeping their meaning; where an answer gives a general figure and the unit card gives its own figure, use the unit card's figure.", ""]
    for title, qas in groups:
        out += [f"### {title}", ""]
        for q, ans in qas:
            out += [f"**Q: {q}**", ""] + ans + [""]
    text = "\n".join(out).rstrip() + "\n"
    assert "—" not in text, "em dash in water.md"
    (KB / "categories/water.md").write_text(text, encoding="utf-8")

    e = ["# Edits to the Water Q&A text", "",
         "Every change made to the client's wording in `Water_Truck_AI_Advisor.docx`, generated by `phase-2/tools/build_water.py`. Everything not listed here is word for word, except that the document header and the per-group \"Status:\" lines are left out and the \"Answer:\" labels are removed.", ""]
    for q, old, new, why in log:
        e += [f"## {q}", "", f"- **Was:** {old}", f"- **Now:** {new}", f"- **Why:** {why}", ""]
    (KB / "EDITS-WATER.md").write_text("\n".join(e).rstrip() + "\n", encoding="utf-8")
    print(f"built Water: {sum(counts)} questions, {len(log)} edits")


if __name__ == "__main__":
    main()
